def write(rid):
    spec = RIGS[rid]
    p = os.path.join(ROOT, "data", "art", "rigs", rid + ".json")
    raw = open(p, encoding="utf-8", newline="").read()
    d = json.loads(raw)
    d["parts"] = spec["parts"]
    d["ground_px"] = spec["ground_px"]
    if "_source" in d and "v2 painting" not in d["_source"]:
        d["_source"] += " Story 053: outlines redrawn for the v2 painting (tools/art/rig_parts_v2.py)."
    out = json.dumps(d, indent=1, ensure_ascii=False)
    if "\r\n" in raw:
        out = out.replace("\n", "\r\n")
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print("%s: %d parts" % (rid, len(spec["parts"])))


for rid in sys.argv[1:] or RIGS.keys():
    write(rid)
